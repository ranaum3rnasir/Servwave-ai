-- Roles & Permissions alignment, AL-01a (P14, M3): a person's stored switches become OVERRIDES only.
--
-- Until now giving a person a role copied every switch value into permission_user_switches, so a later role edit
-- reached nobody. From this release a person's effective value is their own row if they have one, else their role's;
-- a row exists only where the person holds a value that DIFFERS from their role.
--
-- This migration deletes, for every person outside the Admin box, each row whose value equals the value their role
-- holds today (the role's stored row, else the preset of the role's built-in base, else the narrowest value for a role
-- made from blank). A person's effective value does not change: only the redundant copy goes. A row whose value
-- differs from the role stays, because it is a real override. The deletion writes NO permission_change_log row:
-- nobody's access changes (each deleted value equals the role's), the same rule as migration 20261028100500. A row
-- per dropped copy would read "X -> X" on every person's Change log and, once the log is append-only
-- (20261028140000), could never be removed.
--
-- Rollback: re-copy the role's value into permission_user_switches for each person and switch. Nothing is lost,
-- because every deleted row held exactly the value its role holds.
--
-- The preset table below is a SNAPSHOT of the catalog presets at the time of this migration, for roles that hold no
-- stored row for a switch. It is frozen and never regenerated.
--
-- IDEMPOTENT: a second run finds no row equal to its role and changes nothing. SET-BASED: one DELETE statement.
-- Portable plain PostgreSQL. NEVER run `prisma migrate` from a worktree.

