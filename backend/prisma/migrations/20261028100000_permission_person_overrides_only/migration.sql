  -- Each person with the role key and the built-in preset behind it.
  CREATE TEMP TABLE al_01a_person ON COMMIT DROP AS
  SELECT u.id AS user_id,
         u.organization_id,
         COALESCE(u.based_on_role_key, cr.key, u.role::text) AS role_key,
         CASE
           WHEN COALESCE(u.based_on_role_key, cr.key, u.role::text) IN ('ADMIN', 'SALES', 'DISPATCHER', 'TECHNICIAN')
             THEN COALESCE(u.based_on_role_key, cr.key, u.role::text)
           WHEN bcr.id IS NULL THEN u.role::text
           WHEN bcr.made_from_blank THEN 'BLANK'
           ELSE bcr.base_role::text
         END AS preset_role
  FROM users u
  LEFT JOIN custom_roles cr ON cr.id = u.custom_role_id
  LEFT JOIN custom_roles bcr
         ON bcr.organization_id = u.organization_id
        AND bcr.key = COALESCE(u.based_on_role_key, cr.key, u.role::text)
  -- The Admin box (built-in Admin, no custom role) holds every switch and no stored set.
  WHERE NOT (u.role::text = 'ADMIN' AND u.custom_role_id IS NULL);

  DELETE FROM permission_user_switches uv
  USING al_01a_person p
  WHERE uv.user_id = p.user_id
    AND uv.value = COALESCE(
      (SELECT rs.value FROM permission_role_switches rs
        WHERE rs.organization_id = p.organization_id AND rs.role_key = p.role_key AND rs.switch_key = uv.switch_key),
      (SELECT pr.value FROM al_01a_preset pr WHERE pr.preset_role = p.preset_role AND pr.switch_key = uv.switch_key)
    );
END
